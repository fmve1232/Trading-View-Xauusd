"""Generate docs/DASHBOARD_FIELD_MAP.md from site/bbg.js (mandate 2026-11-28, Part 19 items 2-4): every cell of the
terminal band, its source field(s), how it is formed and how often it updates, plus the known gaps. The table is read
from the FIELDS and GAPS objects in bbg.js with Node, so the document cannot drift from the code.

  python audit/tools/dashboard_field_map.py [--root <repo>] [--check]
--check exits 1 if the document on disk differs from what bbg.js gives.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = "docs/DASHBOARD_FIELD_MAP.md"


def read_fields(root: str) -> dict:
    js = ("const B = require(process.argv[1]);"
          "console.log(JSON.stringify({fields: B.FIELDS, gaps: B.GAPS, sections: B.SECTIONS, words: B.WORDS}));")
    r = subprocess.run(["node", "-e", js, os.path.join(root, "site", "bbg.js")], capture_output=True, text=True, check=True)
    return json.loads(r.stdout)


def cell(s: str) -> str:
    return str(s).replace("|", "\\|")


def build(spec: dict) -> str:
    F, G = spec["fields"], spec["gaps"]
    L = ["# Dashboard field map: the terminal band (sections A-I)", "",
         ("Generated by `audit/tools/dashboard_field_map.py` from `site/bbg.js` (`FIELDS`, `GAPS`); `--check` confirms this "
          "file matches the code. Mandate 2026-11-28, Parts 18-19. The band is display only: `bbg.js` lays out what the "
          "pipeline published in `data/<tf>.json` and `data/index.json`, and what `app.js` already derives (freshness, the "
          "live quote, the RECORD verdict, the WAIT wording, the trend-vote wording, the MT5 offset), which it is handed. "
          "It computes no signal, score or probability."), "",
         ("Status words, used whenever a value is missing or unvalidated: " + ", ".join(f"`{w}`" for w in spec["words"].values())
          + "; also `INDICATIVE` (futures standing in for spot), `CLOSED` (market shut) and `SYNTHETIC` (simulated data)."), "",
         "Field paths are in `data/<tf>.json` unless they start with `alerts.` (that is `data/index.json`).", "",
         ("'Each engine run' = the pipeline's 15-minute schedule; the page picks a new run up within 20 s, re-renders the band "
          "every 15 s, and at most once a second while live quotes arrive."), ""]
    for sec, title in spec["sections"]:
        L += [f"## {sec}. {title.title()}", "", "| Cell | Source field(s) | How the cell is formed | Updates |", "|---|---|---|---|"]
        for fid, (s, label, src, calc, freq) in F.items():
            if s == sec:
                L.append(f"| `{fid}` {cell(label)} | {cell(src)} | {cell(calc)} | {cell(freq)} |")
        L.append("")
    L += ["## Known gaps (Part 19 item 4)", "", "| Cell | Gap |", "|---|---|"]
    L += [f"| `{fid}` {cell(F[fid][1])} | {cell(why)} |" for fid, why in G.items()]
    L += ["", f"{len(F)} cells in {len(spec['sections'])} sections; {len(G)} gap entries.", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    doc = build(read_fields(a.root))
    out = os.path.join(a.root, OUT)
    if a.check:
        same = False
        if os.path.exists(out):
            with open(out, encoding="utf-8") as fh:
                same = fh.read() == doc
        print("field map matches site/bbg.js" if same else "field map DIFFERS from site/bbg.js")
        return 0 if same else 1
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(doc)
    return 0


if __name__ == "__main__":
    sys.exit(main())
