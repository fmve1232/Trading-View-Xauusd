"""Writes the results block of docs/final_audit/G4_TRADE_DIAGNOSTICS.md from the committed G4 evidence files, so no
number in it is typed by hand (operator mandate, 27 Nov 2026: "Every reported number must be generated from evidence
files").

  python3 audit/tools/g4_doc.py [--day 2026-11-27] [--check]
Reads docs/final_audit/evidence/g4_*_<day>.* and replaces the text between the G4:BEGIN / G4:END markers.
--check: exit 1 if the committed block differs from what the evidence gives (tests/test_trade_diag.py runs this).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, ROOT)
from quantum import trade_diag as TD  # the table formatter; it reads nothing

EV = os.path.join(ROOT, "docs", "final_audit", "evidence")
DOC = os.path.join(ROOT, "docs", "final_audit", "G4_TRADE_DIAGNOSTICS.md")
BEGIN, END = "<!-- G4:BEGIN (generated by audit/tools/g4_doc.py; do not edit) -->", "<!-- G4:END -->"


def _load(name: str):
    with open(os.path.join(EV, name)) as f:
        return json.load(f) if name.endswith(".json") else f.read()


def _sum(summary: dict, get) -> dict:
    out: dict = {}
    for v in summary.values():
        for k, n in get(v).items():
            out[k] = out.get(k, 0) + n
    return dict(sorted(out.items()))


def block(day: str) -> str:
    run = _load(f"g4_trade_diag_{day}.txt").splitlines()
    head = {x.split(":", 1)[0]: x.split(":", 1)[1].strip() for x in run[1:5] if ":" in x}
    app = json.loads(next(x for x in run if x.startswith('{"state"')))
    before = next(x for x in run if x.startswith("ledgers sha256") and "before" in x).rsplit(" ", 1)[1]
    after = next(x for x in run if x.startswith("ledgers sha256") and "after" in x).rsplit(" ", 1)[1]
    rec = next(x for x in run if x.startswith("records file:")).split()
    chk, raw = _load(f"g4_trade_diag_check_{day}.json"), _load(f"g4_trade_diag_check_raw_{day}.json")
    mut = _load(f"g4_mutation_{day}.json")
    s = _load(f"g4_trade_diag_summary_{day}.json")
    n = sum(v["n"] for v in s.values())
    win = _sum(s, lambda v: v["race_window_ends"])
    ends = _sum(s, lambda v: v["in_trade_ends"])
    news = _sum(s, lambda v: v["news"])
    close = sum(v["next_open"]["filled_at_a_session_close"] for v in s.values())
    measured = sum(v["cost_measured"] for v in s.values())
    killed = sum(1 for v in mut.values() if v)
    lines = [
        BEGIN,
        "",
        "### Run",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Store | {head.get('store', '')} |",
        f"| Run time | {head.get('run time (--now)', '')} |",
        f"| Code | {head.get('code', '')} |",
        f"| Closed ledger trades | {app['closed_trades']} |",
        f"| Records written | {app['appended']} |",
        f"| Pending (race undecided, horizon open) | {app['pending']} |",
        f"| Records file | `{rec[3]}`, SHA-256 `{rec[2]}`, {rec[5]} lines |",
        (f"| Ledgers before / after (SHA-256 of all `holdout/*.json`) | `{before[:16]}…` / `{after[:16]}…`: "
         f"{'byte-identical' if before == after else 'CHANGED'} |"),
        "",
        "### Validation",
        "",
        "| Check | Result |",
        "|---|---|",
        (f"| Independent recomputation ({chk['bars']}) | {chk['agree']} of {chk['records']} agree; "
         f"{chk['disagree']} disagree; {chk['ledger_changed']} ledger trades changed |"),
        (f"| Same, raw feed bars | {raw['agree']} of {raw['records']} agree; {raw['reopen_only']} differ only at a "
         f"session reopen; {raw['disagree']} disagree |"),
        f"| Mutation test (`audit/tools/mutation_trade_diag.py`) | {killed} of {len(mut)} mutants killed |",
        "",
        "Records whose raw-feed result differs, all at a session reopen (the repaired first print is the engine's):",
        "",
    ]
    lines += [f"- `{d['key']}`: {'; '.join(d['diffs'])}" for d in raw["details"]] or ["- none"]
    lines += [
        "",
        "### Totals over all arms and timeframes",
        "",
        "| Item | Count |",
        "|---|---|",
        f"| Records | {n} |",
        *[f"| Race window ended: {k} | {v} |" for k, v in win.items()],
        *[f"| In-trade window: {k} | {v} |" for k, v in ends.items()],
        f"| Signal filled at a session close (engine fill while the market was shut) | {close} |",
        f"| Cost measured from broker fills | {measured} (no broker fills yet: G2) |",
        f"| Covered by the NFP / CPI / FOMC calendar | {news.get('covered', 0)} |",
        f"| On a New York news day | {news.get('news_day', 0)} |",
        f"| Event inside the trade | {news.get('event_in_trade', 0)} |",
        f"| Fill within the ±30 min window | {news.get('fill_in_window', 0)} |",
        "",
        "### Per arm and timeframe",
        "",
        ("Rates are target-before-stop among decided races, against the original stop, with Wilson 95% intervals. "
         "Descriptive only: no baseline and no test here; the matched random-entry comparison is reported separately."),
        "",
        TD.markdown(s),
        "",
        END,
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--day", default="2026-11-27")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    with open(DOC) as f:
        doc = f.read()
    i, j = doc.index(BEGIN), doc.index(END) + len(END)
    new = doc[:i] + block(a.day) + doc[j:]
    if a.check:
        ok = new == doc
        print("G4 document matches the evidence" if ok else "G4 document differs from the evidence: run audit/tools/g4_doc.py")
        return 0 if ok else 1
    with open(DOC, "w") as f:
        f.write(new)
    print("written", os.path.relpath(DOC, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
