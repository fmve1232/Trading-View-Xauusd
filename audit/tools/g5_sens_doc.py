"""Generate research/G5_SENS_RESULTS.md from research/G5_SENS_RESULTS.json (the run file of
quantum/research/g5_sens.py). Every number is read from that file; nothing is typed in.

  python audit/tools/g5_sens_doc.py [--root <repo>] [--check]
--check exits 1 if the document on disk differs from what the run file gives.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
RUN = "research/G5_SENS_RESULTS.json"
OUT = "research/G5_SENS_RESULTS.md"


def num(x, nd=4):
    return "n/a" if x is None else f"{x:+.{nd}f}"


def ci(x):
    return "n/a" if not x or x[0] is None else f"[{x[0]:+.4f}, {x[1]:+.4f}]"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def pf(p):
    return "n/a" if p is None else ("< 0.0001" if p < 1e-4 else f"{p:.4f}")


def build(r: dict) -> str:
    cells = r["cells"]
    frozen = [c for c in cells if c["group"] == "frozen"]
    m_all = [c["m"] for c in cells if c["m"].get("n")]
    pos = sum(1 for m in m_all if (m.get("mean_net_r") or 0) > 0)
    lo_pos = sum(1 for m in m_all if m.get("mean_net_r_day_boot95") and m["mean_net_r_day_boot95"][0] > 0)
    holm = sum(1 for m in m_all if m.get("p_holm") is not None and m["p_holm"] < 0.05)
    bh = sum(1 for m in m_all if m.get("p_bh") is not None and m["p_bh"] < 0.05)
    L = ["# G5-SENS: one-at-a-time parameter sensitivity of the frozen engine (development data only)", "",
         (f"Generated by `audit/tools/g5_sens_doc.py` from `{RUN}` (the run file of `quantum/research/g5_sens.py`); "
          "`--check` confirms this file matches it. Registration: `research/registrations/G5-SENS.json` and its amendment "
          "A1, both committed before any code or run."), "",
         (f"**Decision:** {r['decision']}. No cell is selected, recommended or adopted. The frozen configuration and the "
          "freeze key are unchanged. This study reads one partition many times, so it cannot serve as evidence for any "
          "change."), "",
         "## Run", "",
         f"- Partition: {r['partition']}, {r['window'][0]} to {r['window'][1]}; data hashes {r['data_hashes']}; seed {r['seed']}.",
         f"- Cells: {r['cells_run']} of {r['cells_planned']} planned, every one run and kept (failed or negative cells included).",
         f"- Engine runs: {len(r['engine_seconds'])}, {sum(r['engine_seconds'].values()):,.0f} s in total.", "",
         "## Headline counts over all cells", "",
         f"- Cells with trades: {len(m_all)}. Mean net R above zero: **{pos}**. Day-block 95% interval wholly above zero: **{lo_pos}**.",
         (f"- One-sided t-test of mean net R > 0, adjusted across all {len(m_all)} cells: Holm p < 0.05 in **{holm}** "
          f"cells, Benjamini-Hochberg p < 0.05 in **{bh}**."), "",
         "## The frozen engine on the development partition", "",
         ("| TF | Arm | n | Mean net R [95% days] | Mean gross R | Win rate | PF | Max DD R | Share <= -1 R | "
          "+$10 / +$15 / +$20 before stop |"), "|---|---|---|---|---|---|---|---|---|---|"]
    for c in frozen:
        m = c["m"]
        t = m.get("targets") or {}
        L.append(f"| {c['tf']} | {c['arm']} | {m.get('n')} | {num(m.get('mean_net_r'))} {ci(m.get('mean_net_r_day_boot95'))} | "
                 f"{num(m.get('mean_gross_r'))} | {pct(m.get('win_rate'))} | {m.get('pf')} | {m.get('max_dd_r')} | "
                 f"{pct(m.get('share_at_or_below_minus_1r'))} | "
                 + " / ".join(pct((t.get(k) or {}).get('rate')) for k in ("usd10", "usd15", "usd20")) + " |")
    L += ["", ("Targets are scaled by P0 / 4000 (the registered convention) and raced from the fill on 5-minute bars; a "
               "bar touching both counts as the stop."), "",
          "## Fragility per parameter (stated in advance: sign stability, the frozen value's rank, PEAK / PLATEAU / SLOPE)", "",
          "| TF | Arm | Parameter | Values | Mean net R per value | n per value | Frozen rank | Shape | Sign stable | Max change | Intervals overlap |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for f in r["fragility"]:
        if "note" in f:
            L.append(f"| {f['tf']} | {f['arm']} | {f['param']} | {f['note']} | | | | | | | |")
            continue
        L.append(f"| {f['tf']} | {f['arm']} | {f['param']} | {', '.join(str(v) for v in f['values'])} | "
                 f"{', '.join(num(x) for x in f['mean_net_r'])} | {', '.join(str(n) for n in f['n'])} | {f['frozen_rank']} | "
                 f"{f['shape']} | {f['sign_stable']} | {f['max_abs_change_mean_net_r']} | {f['intervals_overlap_frozen']} |")
    shapes = {}
    for f in r["fragility"]:
        shapes[f.get("shape", "NOTE")] = shapes.get(f.get("shape", "NOTE"), 0) + 1
    L += ["", "Shapes: " + ", ".join(f"{k} {v}" for k, v in sorted(shapes.items())) + ".", "",
          "## Cost sensitivity", "",
          "Registered cost cells (the configuration's cost inputs multiplied; the session spread floor still applies):", "",
          "| TF | Arm | Cost multiplier | n | Mean net R [95% days] |", "|---|---|---|---|---|"]
    for c in cells:
        if c["group"] == "cost":
            L.append(f"| {c['tf']} | {c['arm']} | {c['value']} | {c['m'].get('n')} | {num(c['m'].get('mean_net_r'))} "
                     f"{ci(c['m'].get('mean_net_r_day_boot95'))} |")
    L += ["", "Supplementary, the frozen cells' own trades re-priced at fixed signals (A1, not a cell):", "",
          "| TF | Arm | x 0.5 | x 1.5 | x 2.0 |", "|---|---|---|---|---|"]
    for c in frozen:
        s = {x["mult"]: x["mean_net_r"] for x in c.get("supplementary_cost_repriced", [])}
        L.append(f"| {c['tf']} | {c['arm']} | {num(s.get(0.5))} | {num(s.get(1.5))} | {num(s.get(2.0))} |")
    L += ["", "## By regime and session (frozen cells; the trade record's own labels)", ""]
    for c in frozen:
        by = c["m"].get("by") or {}
        for k in ("regime", "session"):
            if by.get(k):
                L.append(f"- {c['tf']} {c['arm']} by {k}: " + "; ".join(
                    f"{lab} n {v['n']} mean {num(v['mean_net_r'])}" for lab, v in sorted(by[k].items())))
    L += ["", "## Every cell (failed and negative cells included)", "",
          "| TF | Arm | Group | Parameter | Value | n | Mean net R [95% days] | Win rate | p (one-sided) | Holm | BH |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in cells:
        m = c["m"]
        L.append(f"| {c['tf']} | {c['arm']} | {c['group']} | {c['param'] or ''} | {'' if c['value'] is None else c['value']} | "
                 f"{m.get('n')} | {num(m.get('mean_net_r'))} {ci(m.get('mean_net_r_day_boot95'))} | {pct(m.get('win_rate'))} | "
                 f"{pf(m.get('p_one_sided'))} | {pf(m.get('p_holm'))} | {pf(m.get('p_bh'))} |")
    L += ["", "## Limits", "",
          "- One partition, read many times. A cell that looks better here is a hypothesis for a new registration, not a result.",
          ("- The development market has no external series, so the engine's macro terms are inactive; the arms tested "
           "here are the frozen engine without its macro inputs."),
          "- Costs are the engine's MODELLED cost of record; the broker's costs are unverified (G2).",
          "- 30m is resampled from 15m on this partition; production fetches 30-minute bars."]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    with open(os.path.join(a.root, RUN)) as fh:
        doc = build(json.load(fh))
    out = os.path.join(a.root, OUT)
    if a.check:
        same = os.path.exists(out) and _read(out) == doc
        print("document matches the run file" if same else "document DIFFERS from the run file")
        return 0 if same else 1
    with open(out, "w") as fh:
        fh.write(doc)
    return 0


def _read(path: str) -> str:
    with open(path) as fh:
        return fh.read()


if __name__ == "__main__":
    sys.exit(main())
