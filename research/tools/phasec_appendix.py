"""Builds research/PHASE_C_APPENDIX.md from the committed results only (no number typed by hand): the corrected re-runs'
reproduction check, the top-q selection audit, the Phase C tables (leaderboards A / B / C, BUY / SELL, named bests,
diagnostics), every shortlisted candidate with the acceptance criteria, and the risk table.

  python research/tools/phasec_appendix.py > research/PHASE_C_APPENDIX.md
"""
import subprocess
import sys

R = "research/results"
STEPS = (
    ("A1. Reproduction of the registered runs by the corrected re-runs",
     ["research/tools/phasec_rerun_compare.py", f"{R}/b27", f"{R}/b27_fix", f"{R}/b29", f"{R}/b29_fix"]),
    ("A2. Top-q selection audit (corrected: raw-score ranking)",
     ["research/tools/phasec_topq_audit.py", "--out", f"{R}/phasec/topq_audit.json", "--markdown", f"{R}/b27_fix/b27_summary.json",
      f"{R}/b29_fix/b29_summary.json", f"{R}/b27/b27_summary.json", f"{R}/b29/b29_summary.json"]),
    ("A3. Phase C tables: counts, grid, resolution, V / M / C / E, B28, leaderboards, named bests, diagnostics (corrected runs)",
     ["research/tools/phasec_tables.py", f"{R}/b27_fix/b27_summary.json", f"{R}/b28/b28_summary.json", f"{R}/b29_fix/b29_summary.json",
      f"{R}/phasec"]),
    ("A4. Every shortlisted candidate and the six acceptance criteria", ["-c", f"print(open('{R}/phasec/candidates.md').read())"]),
    ("A5. Risk and position sizing (measured grid, 0.50 lot ASSUMED 100 oz)", ["research/tools/phasec_risk.py", f"{R}/b29/b29_grid.csv"]),
)


def main() -> int:
    print("# Phase C appendix (generated by `research/tools/phasec_appendix.py`; do not edit by hand)\n")
    print("Every table below is printed by a tool from the committed files in `research/results/`. "
          "The narrative is in `PHASE_C_REPORT.md`, `B27_RESULTS.md` (erratum), `B28_RESULTS.md` and `B29_RESULTS.md`.\n")
    for title, cmd in STEPS:
        r = subprocess.run([sys.executable, *cmd], capture_output=True, text=True, check=False)
        if r.returncode not in (0,):
            raise SystemExit(f"{title}: {' '.join(cmd)} failed ({r.returncode}):\n{r.stderr[-2000:]}")
        print(f"\n## {title}\n")
        print(r.stdout.rstrip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
